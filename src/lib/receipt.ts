import { formatCurrency, formatDate } from './utils';

/** Escape user-supplied strings before interpolating into receipt HTML —
 *  tenant names and addresses are entered by other users and could carry markup. */
function esc(s: string): string {
  return s
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');
}

export interface ReceiptData {
  receiptNo: string;
  paidAt: string;
  dueDate: string;
  amount: number;
  method: string;
  propertyAddress: string;
  tenantName: string;
}

/**
 * Opens a clean, printable rent receipt in a new window. Renters need these for
 * references, disputes, and taxes; "Save as PDF" from the print dialog gives them
 * a permanent copy without us bundling a PDF library.
 */
export function printRentReceipt(d: ReceiptData) {
  const html = `<!doctype html><html><head><meta charset="utf-8" />
<title>Rent Receipt ${esc(d.receiptNo)}</title>
<style>
  body { font-family: system-ui, -apple-system, Segoe UI, sans-serif; color: #111; max-width: 600px; margin: 40px auto; padding: 0 24px; }
  h1 { font-size: 20px; margin: 0 0 4px; }
  .muted { color: #6b7280; font-size: 13px; }
  .row { display: flex; justify-content: space-between; padding: 10px 0; border-bottom: 1px solid #eee; font-size: 14px; }
  .label { color: #6b7280; }
  .total { font-size: 22px; font-weight: 700; margin-top: 16px; }
  .brand { color: #0D1F2D; font-weight: 700; }
  .paid { display:inline-block; margin-top:12px; padding:4px 10px; border-radius:999px; background:#dcfce7; color:#15803d; font-size:12px; font-weight:700; }
  @media print { button { display: none; } }
</style></head><body>
  <p class="brand">HappyHomesHub</p>
  <h1>Rent Receipt</h1>
  <p class="muted">Receipt #${esc(d.receiptNo)}</p>
  <span class="paid">PAID</span>
  <div style="margin-top:20px">
    <div class="row"><span class="label">Tenant</span><span>${esc(d.tenantName)}</span></div>
    <div class="row"><span class="label">Property</span><span>${esc(d.propertyAddress)}</span></div>
    <div class="row"><span class="label">For period due</span><span>${formatDate(d.dueDate)}</span></div>
    <div class="row"><span class="label">Paid on</span><span>${formatDate(d.paidAt)}</span></div>
    <div class="row"><span class="label">Method</span><span>${esc(d.method.replace('_', ' '))}</span></div>
  </div>
  <p class="total">${formatCurrency(d.amount)}</p>
  <p class="muted" style="margin-top:24px">Generated by HappyHomesHub on ${formatDate(new Date().toISOString())}.</p>
  <button onclick="window.print()" style="margin-top:24px;padding:10px 18px;border:0;border-radius:10px;background:#0D1F2D;color:#fff;font-weight:600;cursor:pointer">Print / Save as PDF</button>
</body></html>`;

  const w = window.open('', '_blank');
  if (!w) return false;
  w.document.write(html);
  w.document.close();
  return true;
}
